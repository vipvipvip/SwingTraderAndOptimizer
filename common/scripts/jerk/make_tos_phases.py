#!/usr/bin/env python3
"""Generate a thinkScript phase-marker study for a ticker from the Python detectors.

    python3 make_tos_phases.py ZS [MRNA ...] [--from 2023-01-01]  -> common/tos/jerk_<t>_phases.ts

Dates are copied from explosion.py (daily drawdown->trough->base->imminent pipeline) and
weekly_experiment.py (weekly 'pasted rule'); thinkScript does not recompute anything.
"""
import argparse
import os

import pandas as pd

import explosion as x
import weekly_experiment as w

OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'tos')
f8 = lambda d: d.strftime('%Y%m%d')


def cond(dates):
    return "\n    or ".join(f"({v} > pd and {v} <= d)" for v in dates) if dates else "no"


def build(ticker, start):
    df = x.get_daily(x.get_db(), ticker)
    ev = [e for e in x.detect(df) if e['date'] >= start]
    tr = [e for e in ev if e['kind'] == 'trough']
    lows = [f8(e['low_date']) for e in tr]
    conf = [f8(e['date']) for e in tr]
    peaks = sorted({f8(e['peak_date']) for e in tr})
    base = [f8(e['date']) for e in ev if e['kind'] == 'base']
    fire = [f8(e['date']) for e in ev if e['kind'] == 'fire']
    wk = w.load(ticker)
    fe = w.build(wk)
    flag = w.variants(fe)['pasted rule'].loc[start:].fillna(False)
    g = w.fwd_gain(fe['c'], 4)
    last = lambda m: f8(df.loc[m:m + pd.Timedelta(days=4)].index[-1])   # week's last trading day
    mons = list(flag[flag].index)
    hit = [last(m) for m in mons if g[m] >= 0.2]
    miss = [last(m) for m in mons if not g[m] >= 0.2]    # includes weeks too recent to score
    T = ticker.upper()
    return f"""# {T} jerk/base/imminent PHASES -- visual check of common/scripts/jerk/ output.
# GENERATED by make_tos_phases.py (from {start.date()}) -- do not hand-edit; regenerate.
#
# Dates are HARD-CODED from the Python detectors (explosion.py daily pipeline and
# weekly_experiment.py 'pasted rule'), NOT recomputed here. Valid for {T} only.
# Works on DAILY or WEEKLY charts: a marker lands on the bar whose period (previous
# bar's date, this bar's date] contains the event date (weekly bars carry one date).
#
#   Gray down-arrow    : drawdown peak
#   Cyan up-arrow      : actual trough LOW (found in hindsight)
#   Yellow point       : trough CONFIRMED date (what a no-lookahead scan knows)
#   Orange square      : base qualified
#   Magenta arrow+bubble: IMMINENT fire (daily pipeline)
#   Green up-arrow (under bar): weekly-rule flag, marked on the week's last trading day; >=+20% within 4 wks (eval only)
#   Gray up-arrow (under bar) : weekly-rule flag with no such follow-through (or too recent to score)
declare upper;

def d = GetYYYYMMDD();
def pd = if IsNaN(d[1]) then 0 else d[1];

def isLow  = {cond(lows)};
def isConf = {cond(conf)};
def isBase = {cond(base)};
def isFire = {cond(fire)};
def isPeak = {cond(peaks)};

plot MkPeak = if isPeak then high else Double.NaN;
MkPeak.SetPaintingStrategy(PaintingStrategy.ARROW_DOWN);
MkPeak.SetDefaultColor(Color.GRAY);
MkPeak.SetLineWeight(3);

plot MkLow = if isLow then low else Double.NaN;
MkLow.SetPaintingStrategy(PaintingStrategy.ARROW_UP);
MkLow.SetDefaultColor(Color.CYAN);
MkLow.SetLineWeight(3);

plot MkConf = if isConf then close else Double.NaN;
MkConf.SetPaintingStrategy(PaintingStrategy.POINTS);
MkConf.SetDefaultColor(Color.YELLOW);
MkConf.SetLineWeight(4);

plot MkBase = if isBase then close else Double.NaN;
MkBase.SetPaintingStrategy(PaintingStrategy.SQUARES);
MkBase.SetDefaultColor(Color.ORANGE);
MkBase.SetLineWeight(3);

plot MkFire = if isFire then low else Double.NaN;
MkFire.SetPaintingStrategy(PaintingStrategy.ARROW_UP);
MkFire.SetDefaultColor(Color.MAGENTA);
MkFire.SetLineWeight(5);

def hitWk = {cond(hit)};
def missWk = {cond(miss)};
plot WkHit = hitWk;
WkHit.SetPaintingStrategy(PaintingStrategy.BOOLEAN_ARROW_UP);
WkHit.SetDefaultColor(Color.GREEN);
WkHit.SetLineWeight(4);
plot WkMiss = missWk;
WkMiss.SetPaintingStrategy(PaintingStrategy.BOOLEAN_ARROW_UP);
WkMiss.SetDefaultColor(Color.GRAY);
WkMiss.SetLineWeight(2);

AddChartBubble(isFire, high, "IMMINENT", Color.MAGENTA, yes);
""", dict(troughs=len(tr), bases=len(base), fires=fire, weekly_hits=hit, weekly_flags=len(mons))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('tickers', nargs='+')
    ap.add_argument('--from', dest='start', default='2023-01-01')
    a = ap.parse_args()
    for t in a.tickers:
        src, info = build(t.upper(), pd.Timestamp(a.start))
        p = os.path.join(OUT, f'jerk_{t.lower()}_phases.ts')
        open(p, 'w').write(src)
        print(os.path.normpath(p), info)


if __name__ == '__main__':
    main()
